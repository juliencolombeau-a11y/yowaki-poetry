import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = process.cwd()
const inputPath = resolve(root, 'correspondance-import.json')
const outputDir = resolve(root, '.data')
const outputPath = resolve(outputDir, 'poems-data.sql')

const input = JSON.parse(await readFile(inputPath, 'utf8'))
const poems = input.poems

if (!Array.isArray(poems) || poems.length === 0) {
  throw new Error('Le fichier de correspondance ne contient aucun poème.')
}

function sqlString(value) {
  if (value === null || value === undefined || value === '') {
    return 'NULL'
  }

  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlInteger(value) {
  return Number.isInteger(value) ? String(value) : 'NULL'
}

function sqlBoolean(value) {
  return value ? '1' : '0'
}

function uniqueValues(values) {
  return [...new Set(values.filter((value) => typeof value === 'string' && value.trim()))]
}

const now = Math.floor(Date.now() / 1000)
const languageByName = new Map()
for (const poem of poems) {
  const language = poem.language?.trim()
  if (language) {
    languageByName.set(language, language)
  }
}

const statements = [
  '-- Generated by npm run data:export. Do not edit manually.',
  'PRAGMA foreign_keys = ON;',
  'BEGIN TRANSACTION;',
]

for (const poem of poems) {
  const meter = poem.meterAndRhyme?.split(' / ')[0] ?? null
  const rhymeScheme = poem.meterAndRhyme?.split(' / ').slice(1).join(' / ') || null
  const creationDate = poem.date || null
  const legacyId = sqlInteger(poem.legacyId)
  statements.push(
    [
      'INSERT INTO poems',
      '(legacy_id, document_order, title, body, excerpt, collection, form, stanza, meter, rhyme_scheme, is_calligram, content_type, creation_date, notes, created_at, updated_at)',
      'VALUES',
      `(${legacyId}, ${sqlInteger(poem.documentOrder)}, ${sqlString(poem.title)}, ${sqlString(poem.body)}, ${sqlString(poem.excerpt)}, ${sqlString(poem.collection)}, ${sqlString(poem.form)}, NULL, ${sqlString(meter)}, ${sqlString(rhymeScheme)}, ${sqlBoolean(poem.isCalligram)}, 'poem', ${sqlString(creationDate)}, NULL, ${now}, ${now})`,
      'ON CONFLICT(document_order) DO UPDATE SET',
      `legacy_id = excluded.legacy_id, title = excluded.title, body = excluded.body, excerpt = excluded.excerpt, collection = excluded.collection, form = excluded.form, stanza = excluded.stanza, meter = excluded.meter, rhyme_scheme = excluded.rhyme_scheme, is_calligram = excluded.is_calligram, content_type = excluded.content_type, creation_date = excluded.creation_date, updated_at = excluded.updated_at;`,
    ].join(' '),
  )
}

for (const language of [...languageByName.keys()].sort((a, b) => a.localeCompare(b, 'fr'))) {
  statements.push(
    `INSERT INTO languages (name) VALUES (${sqlString(language)}) ON CONFLICT(name) DO NOTHING;`,
  )
}

for (const poem of poems) {
  const language = poem.language?.trim()
  if (!language) {
    continue
  }

  statements.push(
    `INSERT INTO poem_languages (poem_id, language_id) SELECT p.id, l.id FROM poems p JOIN languages l ON l.name = ${sqlString(language)} WHERE p.document_order = ${sqlInteger(poem.documentOrder)} ON CONFLICT(poem_id, language_id) DO NOTHING;`,
  )
}

statements.push('COMMIT;')

await mkdir(outputDir, { recursive: true })
await writeFile(outputPath, `${statements.join('\n')}\n`, 'utf8')

console.log(`Export SQL créé : ${outputPath}`)
console.log(`Poèmes exportés : ${poems.length}`)
console.log(`Langues exportées : ${languageByName.size}`)
